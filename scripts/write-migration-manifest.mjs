import { readdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

/**
 * Writes the list of migration folder names into a module the running app can
 * read.
 *
 * `/api/health` reported `schemaUpToDate: true` against a database that was
 * missing a column, and that false reassurance cost real time — it was the one
 * place the build log tells you to look. The check probed two specific things a
 * past migration had added, so it could only ever detect the lag it was written
 * for; the next migration went out and the canary did not move.
 *
 * A list of names cannot go stale that way, because it is regenerated from the
 * migrations directory on every build. `prisma/migrations` is not part of a
 * Next.js server bundle, so it has to be baked in at build time rather than
 * read at runtime.
 *
 * The generated file is committed. It has to exist for `typecheck` and `dev`,
 * neither of which runs the build chain, and a checked-in copy that drifts is
 * caught by CI rather than discovered in production.
 */

const MIGRATIONS_DIR = "prisma/migrations";
const OUT = "src/lib/db/migrations.generated.ts";

const names = readdirSync(MIGRATIONS_DIR, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const contents = `// Generated by scripts/write-migration-manifest.mjs. Do not edit by hand.
// Regenerate with \`npm run migrations:manifest\` after adding a migration.

/** Every migration this build of the code expects to have been applied. */
export const EXPECTED_MIGRATIONS: readonly string[] = ${JSON.stringify(names, null, 2)};
`;

const path = join(process.cwd(), OUT);
const unchanged = existsSync(path) && readFileSync(path, "utf8") === contents;

if (unchanged) {
  console.log(`[manifest] ${OUT} is up to date (${names.length} migrations).`);
} else {
  writeFileSync(path, contents);
  console.log(`[manifest] Wrote ${OUT} (${names.length} migrations).`);
}

// `--check` is for CI: fail rather than write, so a manifest somebody forgot to
// regenerate is a red build instead of a surprise at deploy time.
if (process.argv.includes("--check") && !unchanged) {
  console.error(
    `[manifest] ${OUT} was out of date. Run \`npm run migrations:manifest\` and commit the result.`
  );
  process.exit(1);
}
